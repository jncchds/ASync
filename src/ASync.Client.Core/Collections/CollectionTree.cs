using ASync.Contracts;
using ASync.Engine.Local;

namespace ASync.Client.Core.Collections;

/// <summary>
/// A phone's contacts or calendars as a read-only <see cref="ILocalTree"/> in the <see cref="CollectionLayout"/>, so a Contacts or
/// Calendars folder backs up with the same <c>BackupRunner</c> and <c>BackupJob</c> as a directory (like task 19's <c>MediaTree</c>).
/// The selection is listed once, when the tree is first used. Files are generated (vCard, iCalendar, the JSON beside them):
/// <list type="bullet">
/// <item>with a version from the provider (Android's contacts), a file is listed with its last size (<see cref="GeneratedSizeCache"/>)
/// and the provider's modification time, so an unchanged contact is taken from the parent snapshot without being generated or its
/// photo read; a changed or new one is generated while listing (to know its size) and kept in memory until the backup reads it;</item>
/// <item>without one (Android's events, which have no version), every file is generated while listing and always read
/// (<see cref="AlwaysRead"/>): an unchanged one gives the same bytes and is deduplicated to the stored blob.</item>
/// </list>
/// Writes throw; <see cref="Exists"/> is false without the permission, with <see cref="UnavailableReason"/> saying so.
/// </summary>
public sealed class CollectionTree : ILocalTree
{
    /// <summary>One generated file. <paramref name="Version"/> null: no version, always generated and read.</summary>
    public sealed record GeneratedFile(string Path, long Modified, string? Version, Func<byte[]> Make, bool Item = true);

    private const long KeepInMemory = 48L << 20; // generated bytes kept between listing and reading; beyond, generated again when read

    private readonly FolderKind _kind;
    private readonly Func<MediaAccess> _access;
    private readonly Func<(IReadOnlyList<GeneratedFile> Files, int Collections)> _list;
    private readonly GeneratedSizeCache? _cache;
    private readonly Lazy<Listing> _listing;
    private readonly string _describe;

    private CollectionTree(FolderKind kind, string name, string describe, Func<MediaAccess> access,
        Func<(IReadOnlyList<GeneratedFile>, int)> list, GeneratedSizeCache? cache)
    {
        _kind = kind;
        Name = name;
        _describe = describe;
        _access = access;
        _list = list;
        _cache = cache;
        _listing = new Lazy<Listing>(Build, LazyThreadSafetyMode.ExecutionAndPublication);
    }

    // ── Contacts ─────────────────────────────────────────────────────────────

    /// <param name="source">Recorded in account.json: which provider it came from (<c>android-contacts</c>, later <c>ios-contacts</c>).</param>
    /// <param name="cache">Sizes of the contacts by version (the folder's state directory); null keeps none (every contact generated).</param>
    public static CollectionTree Contacts(IContactsSource contacts, CollectionSelectionDto? selection, string source = "", GeneratedSizeCache? cache = null)
    {
        var sel = selection ?? CollectionSelectionDto.Everything;
        return new CollectionTree(FolderKind.Contacts, "Contacts", $"contacts ({sel.Describe(FolderKind.Contacts)})", () => contacts.Access, () =>
        {
            var accounts = contacts.Accounts().Where(a => sel.All || sel.Collections!.Any(c => c.Id == a.Id)).ToList();
            var byId = accounts.ToDictionary(a => a.Id, StringComparer.Ordinal);
            var files = new List<GeneratedFile>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            var newest = new Dictionary<string, long>(StringComparer.Ordinal);
            foreach (var c in contacts.Contacts(sel.All ? null : byId.Keys.ToHashSet(StringComparer.Ordinal)).OrderBy(c => c.Id, StringComparer.Ordinal))
            {
                if (!byId.TryGetValue(c.AccountId, out var account)) continue;
                var dir = CollectionLayout.AccountDirectory(account);
                var path = $"{dir}/{CollectionLayout.ContactFile(c.DisplayName, c.ShortId)}";
                if (!seen.Add(path)) continue;
                var id = c.Id;
                files.Add(new GeneratedFile(path, c.Modified, c.Version,
                    () => VCard.Write(contacts.Read(id) ?? throw new FileNotFoundException("The contact was deleted while it was backed up."))));
                newest[dir] = Math.Max(newest.GetValueOrDefault(dir), c.Modified);
            }
            foreach (var a in accounts)
            {
                var dir = CollectionLayout.AccountDirectory(a);
                var info = CollectionInfoFile.For(a, source).ToJson();
                files.Add(new GeneratedFile($"{dir}/{CollectionLayout.AccountFile}", newest.GetValueOrDefault(dir), null, () => info, Item: false));
            }
            return (files, accounts.Count);
        }, cache);
    }

    // ── Calendars ────────────────────────────────────────────────────────────

    /// <param name="source">Recorded in calendar.json (<c>android-calendar</c>, later <c>ios-eventkit</c>).</param>
    /// <param name="now">Unix ms: what "events since" counts back from.</param>
    public static CollectionTree Calendars(ICalendarSource calendars, CollectionSelectionDto? selection, long now, string source = "")
    {
        var sel = selection ?? CollectionSelectionDto.Everything;
        long? since = sel.PastDays is { } days ? now - days * 86400000L : null;
        return new CollectionTree(FolderKind.Calendars, "Calendars", $"calendars ({sel.Describe(FolderKind.Calendars)})", () => calendars.Access, () =>
        {
            var chosen = calendars.Calendars().Where(c => sel.All || sel.Collections!.Any(x => x.Id == c.Id)).ToList();
            var byId = chosen.ToDictionary(c => c.Id, StringComparer.Ordinal);
            var files = new List<GeneratedFile>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            var newest = new Dictionary<string, long>(StringComparer.Ordinal);
            foreach (var e in calendars.Events(sel.All ? null : byId.Keys.ToHashSet(StringComparer.Ordinal), since).OrderBy(e => e.Id, StringComparer.Ordinal))
            {
                if (!byId.TryGetValue(e.CalendarId, out var calendar)) continue;
                var dir = CollectionLayout.CalendarDirectory(calendar);
                var path = $"{dir}/{CollectionLayout.EventFile(e)}";
                if (!seen.Add(path)) continue;
                var bytes = ICalendar.Write(e);
                var modified = e.LastModified ?? e.Start;
                files.Add(new GeneratedFile(path, modified, null, () => bytes));
                newest[dir] = Math.Max(newest.GetValueOrDefault(dir), modified);
            }
            foreach (var c in chosen)
            {
                var dir = CollectionLayout.CalendarDirectory(c);
                var info = CollectionInfoFile.For(c, source).ToJson();
                files.Add(new GeneratedFile($"{dir}/{CollectionLayout.CalendarFile}", newest.GetValueOrDefault(dir), null, () => info, Item: false));
            }
            return (files, chosen.Count);
        }, null);
    }

    // ── The tree ─────────────────────────────────────────────────────────────

    private sealed class Listing
    {
        public readonly Dictionary<string, List<LocalEntry>> Directories = new(StringComparer.Ordinal) { [""] = [] };
        public readonly Dictionary<string, GeneratedFile> Files = new(StringComparer.Ordinal);
        public readonly System.Collections.Concurrent.ConcurrentDictionary<string, byte[]> Generated = new(StringComparer.Ordinal);
        public int Items, Collections;
        public long Bytes;
    }

    private Listing Build()
    {
        if (_access() is MediaAccess.None or MediaAccess.Unsupported)
            throw new UnauthorizedAccessException(UnavailableReason ?? "The data cannot be read.");
        var l = new Listing();
        var (files, collections) = _list();
        l.Collections = collections;
        long kept = 0;
        var dirs = new Dictionary<string, long>(StringComparer.Ordinal);
        foreach (var f in files)
        {
            long size;
            if (f.Version is { } version && _cache?.Get(f.Path, version) is { } cached) size = cached;
            else
            {
                byte[] bytes;
                try { bytes = f.Make(); }
                catch (FileNotFoundException) { continue; } // deleted since it was listed
                size = bytes.Length;
                if (f.Version is { } v) _cache?.Set(f.Path, v, size);
                if (f.Version is null || kept + size <= KeepInMemory)
                {
                    l.Generated[f.Path] = bytes;
                    if (f.Version is not null) kept += size;
                }
            }
            l.Files[f.Path] = f;
            if (f.Item) { l.Items++; l.Bytes += size; }
            var slash = f.Path.LastIndexOf('/');
            var dir = f.Path[..slash];
            if (!l.Directories.TryGetValue(dir, out var entries)) l.Directories[dir] = entries = [];
            entries.Add(new LocalEntry(f.Path[(slash + 1)..], LocalEntryKind.File, size, Math.Max(0, f.Modified)));
            dirs[dir] = Math.Max(dirs.GetValueOrDefault(dir), Math.Max(0, f.Modified));
        }
        foreach (var (dir, modified) in dirs) l.Directories[""].Add(new LocalEntry(dir, LocalEntryKind.Directory, 0, modified));
        _cache?.Save(l.Files.Values.Where(f => f.Version is not null).Select(f => f.Path));
        return l;
    }

    /// <summary>What the selection holds: contacts or events, accounts or calendars, bytes (the run's report to the server).</summary>
    public CollectionCountsDto Counts()
    {
        var l = _listing.Value;
        return new CollectionCountsDto(l.Items, l.Collections, l.Bytes);
    }

    public FolderKind Kind => _kind;
    public string Location => _describe;
    public string Name { get; }
    public string? FileSystemPath => null;
    public bool CanSetModified => false;
    public bool Watchable => false;

    public bool Exists() => _access() is MediaAccess.Full or MediaAccess.Partial;

    public string? UnavailableReason => _access() switch
    {
        MediaAccess.None => _kind == FolderKind.Contacts
            ? "ASync may not read the contacts on this device. Allow it in the app: Contacts… on this folder's card."
            : "ASync may not read the calendars on this device. Allow it in the app: Calendars… on this folder's card.",
        MediaAccess.Unsupported => _kind == FolderKind.Contacts ? "This device has no contacts ASync can read." : "This device has no calendars ASync can read.",
        _ => null,
    };

    public bool AlwaysRead(string path) => !_listing.Value.Files.TryGetValue(path, out var f) || f.Version is null;

    public IReadOnlyList<LocalEntry> List(string directory) =>
        _listing.Value.Directories.TryGetValue(directory, out var entries)
            ? entries
            : throw new DirectoryNotFoundException($"{directory} is not in the {(_kind == FolderKind.Contacts ? "contacts" : "calendars")}.");

    public LocalEntry? Stat(string path)
    {
        if (path.Length == 0) return new LocalEntry("", LocalEntryKind.Directory, 0, 0);
        var slash = path.LastIndexOf('/');
        var (dir, name) = slash < 0 ? ("", path) : (path[..slash], path[(slash + 1)..]);
        return _listing.Value.Directories.TryGetValue(dir, out var entries) ? entries.FirstOrDefault(e => e.Name == name) : null;
    }

    public Stream OpenRead(string path)
    {
        var l = _listing.Value;
        if (!l.Files.TryGetValue(path, out var file)) throw new FileNotFoundException($"{path} is not in the backup's listing.");
        if (l.Generated.TryRemove(path, out var bytes)) return new MemoryStream(bytes, writable: false); // a backup reads each file once
        bytes = file.Make();
        if (file.Version is { } v) _cache?.Set(path, v, bytes.Length);
        return new MemoryStream(bytes, writable: false);
    }

    private static NotSupportedException ReadOnly() => new("Contacts and calendars are backed up, never written by a sync.");
    public Stream OpenAppend(string path) => throw ReadOnly();
    public void Move(string from, string to, bool overwrite) => throw ReadOnly();
    public void DeleteFile(string path) => throw ReadOnly();
    public void DeleteDirectory(string path) => throw ReadOnly();
    public bool TrySetModified(string path, long modified) => false;
}
