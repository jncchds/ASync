#!/usr/bin/env bash
# Compiles the iOS head's C# (src/ASync.App.iOS) and its File Provider extension's (src/ASync.App.iOS.FileProvider) on Linux, without the ios workload or Xcode: against the iOS reference
# assemblies (Microsoft.iOS.Ref) and Avalonia.iOS's library, as a plain net10.0 library. It builds no app (no linking,
# no AOT, no bundle, no plists) but catches what most iOS changes break: API names, types, nullability and warnings.
# Run it before pushing iOS work; the real build and the simulator test are .github/workflows/ios.yml on a Mac.
#
#   scripts/check-ios.sh            # warnings are errors, as in CI
#
# IOS_REF_PACK / IOS_REF_VERSION choose the reference pack (default: the one the ios workload of ios.yml installs).
set -euo pipefail

cd "$(dirname "$0")/.."
root=$PWD
pack=${IOS_REF_PACK:-microsoft.ios.ref.net10.0_26.5}
version=${IOS_REF_VERSION:-26.5.10315}
avalonia=$(sed -n 's/.*Include="Avalonia.iOS" Version="\([^"]*\)".*/\1/p' Directory.Packages.props)
work=artifacts/ios-check
packs=$work/packs
mkdir -p "$packs"

fetch() { # id version → directory with the package's contents
  local id=$1 ver=$2 dir="$packs/$1.$2"
  if [ ! -d "$dir" ]; then
    curl -fsSL -o "$dir.nupkg" "https://api.nuget.org/v3-flatcontainer/$id/$ver/$id.$ver.nupkg"
    mkdir -p "$dir" && unzip -q -o "$dir.nupkg" -d "$dir" && rm "$dir.nupkg"
  fi
  echo "$dir"
}

ref=$(fetch "$pack" "$version")/ref/net10.0/Microsoft.iOS.dll
av=$(fetch avalonia.ios "$avalonia")/lib/net10.0-ios26.0/Avalonia.iOS.dll
[ -f "$ref" ] && [ -f "$av" ] || { echo "reference assemblies not found ($ref, $av)" >&2; exit 1; }

cat > "$work/IosCheck.csproj" <<EOF
<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by scripts/check-ios.sh: the iOS head's sources against the iOS reference assemblies. -->
  <PropertyGroup>
    <AssemblyName>ASync.IosCheck</AssemblyName>
    <RootNamespace>ASync.App.iOS</RootNamespace>
    <DefineConstants>\$(DefineConstants);IOS;__IOS__;__MOBILE__;__UNIFIED__</DefineConstants>
    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <!-- Microsoft.iOS.dll is a reference assembly of its own platform. -->
    <NoWarn>\$(NoWarn);MSB3270;CS1701;CS1702</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="$root/src/ASync.App.iOS/**/*.cs" Exclude="$root/src/ASync.App.iOS/obj/**;$root/src/ASync.App.iOS/bin/**" />
    <Compile Include="$root/src/ASync.Tests/Local/LocalTreeContract.cs" />
    <Compile Include="SupportedOn.cs" />
    <!-- The iOS SDK's implicit usings (Microsoft.iOS.Sdk.ImplicitNamespaceImports.props), so ambiguities show here too. -->
    <Using Include="CoreGraphics" />
    <Using Include="Foundation" />
    <Using Include="UIKit" />
    <Reference Include="Microsoft.iOS"><HintPath>$root/$ref</HintPath></Reference>
    <Reference Include="Avalonia.iOS"><HintPath>$root/$av</HintPath></Reference>
    <PackageReference Include="Avalonia" />
    <ProjectReference Include="$root/src/ASync.App/ASync.App.csproj" />
    <ProjectReference Include="$root/src/ASync.Agent/ASync.Agent.csproj" />
  </ItemGroup>
</Project>
EOF
# The platform analyzer then flags APIs newer than the app's minimum (SupportedOSPlatformVersion 15.0).
cat > "$work/SupportedOn.cs" <<'EOF'
[assembly: System.Runtime.Versioning.SupportedOSPlatform("ios15.0")]
EOF

# The File Provider extension (task 25): its own sources and the app's files it links, without Avalonia or the agent, at its
# minimum iOS 16 (NSFileProviderReplicatedExtension).
fp=$root/src/ASync.App.iOS.FileProvider
cat > "$work/IosFileProviderCheck.csproj" <<EOF
<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by scripts/check-ios.sh: the File Provider extension's sources against the iOS reference assemblies. -->
  <PropertyGroup>
    <AssemblyName>ASync.IosFileProviderCheck</AssemblyName>
    <RootNamespace>ASync.App.iOS.FileProvider</RootNamespace>
    <DefineConstants>\$(DefineConstants);IOS;__IOS__;__MOBILE__;__UNIFIED__</DefineConstants>
    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <NoWarn>\$(NoWarn);MSB3270;CS1701;CS1702</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="$fp/**/*.cs" Exclude="$fp/obj/**;$fp/bin/**" />
    <Compile Include="$root/src/ASync.App.iOS/Keychain.cs" />
    <Compile Include="$root/src/ASync.App.iOS/Shared/IosSecrets.cs" />
    <Compile Include="$root/src/ASync.App.iOS/Shared/IosAppGroup.cs" />
    <Compile Include="SupportedOnFileProvider.cs" />
    <Using Include="CoreGraphics" />
    <Using Include="Foundation" />
    <Using Include="UIKit" />
    <Reference Include="Microsoft.iOS"><HintPath>$root/$ref</HintPath></Reference>
    <ProjectReference Include="$root/src/ASync.Client.Core/ASync.Client.Core.csproj" />
  </ItemGroup>
</Project>
EOF
echo '[assembly: System.Runtime.Versioning.SupportedOSPlatform("ios16.0")]' > "$work/SupportedOnFileProvider.cs"

dotnet build "$work/IosCheck.csproj" -nologo -v:q -clp:NoSummary "$@"
dotnet build "$work/IosFileProviderCheck.csproj" -nologo -v:q -clp:NoSummary "$@"
echo "iOS head and File Provider extension compile against $pack $version and Avalonia.iOS $avalonia."
